    'manifestHash',manifest.hash,'modelHash',manifest.modelHash,'fastBudget',c.fastBudget, ...
    'solverBudget',c.solverBudget,'referenceBudget',c.referenceBudget,'qualityStep',c.qualityStep, ...
    'repairBudget',c.repairBudget,'repairIterations',c.repairIterations, ...
    'knownCases',172,'unknownCases',116,'coreCases',32,'matlab',version, ...
    'candidateNoise','Independent candidate-ID streams; exact prefixes across K', ...
    'timing','Task-independent runtime/model loading reported as startup; all task-dependent sampling, building, ranking, required validation, repair and solving counted.'));
end
