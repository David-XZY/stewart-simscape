function q=sgQuality(bundle,task,c)
timer=tic; t=linspace(0,task.T,ceil(task.T/c.qualityStep)+1); h=t(2)-t(1);
tr=sgReconstruct(bundle,t); p=sgPhysics(task.model); m=task.model;
[L,Ld,Ldd,F,~,~,phi]=p.point(tr.q,tr.v,tr.a); L=full(L); Ld=full(Ld); Ldd=full(Ldd); F=full(F); phi=full(phi);
rp=tr.q(5,:); yaw=tr.q(6,:); rd=tr.v(4,:); bd=tr.v(5,:); yd=tr.v(6,:);
rdd=tr.a(4,:); bdd=tr.a(5,:); ydd=tr.a(6,:);
omega=[cos(yaw).*cos(rp).*rd-sin(yaw).*bd;sin(yaw).*cos(rp).*rd+cos(yaw).*bd;-sin(rp).*rd+yd];
alpha=[cos(yaw).*cos(rp).*rdd-sin(yaw).*bdd+(-sin(yaw).*yd.*cos(rp)-cos(yaw).*sin(rp).*bd).*rd-cos(yaw).*yd.*bd; ...
    sin(yaw).*cos(rp).*rdd+cos(yaw).*bdd+(cos(yaw).*yd.*cos(rp)-sin(yaw).*sin(rp).*bd).*rd-sin(yaw).*yd.*bd; ...
    -sin(rp).*rdd+ydd-cos(rp).*bd.*rd];
jerk=derivative(tr.a(1:3,:),h); angularJerk=derivative(alpha,h); legJerk=derivative(Ldd,h); forceRate=derivative(F,h);
reference=sgSpline(dpBaseline(task),t,task.T);
dev=sum(((tr.q-reference.q)./[.1;.1;.1;deg2rad(10)*ones(3,1)]).^2,1);
cost=.1*dev+.3*sum((Ldd/1.2).^2,1)+.4*phi+.08*sum((forceRate/1000).^2,1);
q=struct('positionLengthM',trapz(t,sqrt(sum(tr.v(1:3,:).^2,1))), ...
    'rotationLengthRad',trapz(t,sqrt(sum(omega.^2,1))), ...
    'positionAccelPeak',max(sqrt(sum(tr.a(1:3,:).^2,1))), ...
    'positionAccelRms',sqrt(trapz(t,sum(tr.a(1:3,:).^2,1))/task.T), ...
    'positionJerkPeak',max(sqrt(sum(jerk.^2,1))), ...
    'positionJerkRms',sqrt(trapz(t,sum(jerk.^2,1))/task.T), ...
    'angularAccelPeak',max(sqrt(sum(alpha.^2,1))), ...
    'angularAccelRms',sqrt(trapz(t,sum(alpha.^2,1))/task.T), ...
    'angularJerkPeak',max(sqrt(sum(angularJerk.^2,1))), ...
    'angularJerkRms',sqrt(trapz(t,sum(angularJerk.^2,1))/task.T), ...
    'legAccelPeak',max(abs(Ldd(:))),'legAccelRms',sqrt(trapz(t,mean(Ldd.^2,1))/task.T), ...
    'legJerkPeak',max(abs(legJerk(:))),'legJerkRms',sqrt(trapz(t,mean(legJerk.^2,1))/task.T), ...
    'forcePeakN',max(abs(F(:))),'forceRmsN',sqrt(trapz(t,mean(F.^2,1))/task.T), ...
    'forceRatePeak',max(abs(forceRate(:))),'forceRateRms',sqrt(trapz(t,mean(forceRate.^2,1))/task.T), ...
    'forceSquaredIntegral',trapz(t,sum(F.^2,1)), ...
    'absoluteMechanicalWorkJ',trapz(t,sum(abs(F.*Ld),1)), ...
    'commonCostIntegral',trapz(t,cost),'commonCostMean',trapz(t,cost)/task.T, ...
    'maxSpeedUtilization',max(max(abs(Ld)./m.actuator.ldotMax)), ...
    'maxAccelerationUtilization',max(max(abs(Ldd)./m.actuator.lddotMax)), ...
    'maxForceUtilization',max(max(max(F./m.actuator.forceMax,F./m.actuator.forceMin))), ...
    'minimumLegLengthMargin',min([reshape(L-m.lmin,[],1);reshape(m.lmax-L,[],1)]), ...
    'boundaryError',max(abs([tr.q(:,1)-task.q0;tr.q(:,end)-task.qGoal;reshape(tr.v(:,[1,end]),[],1);reshape(tr.a(:,[1,end]),[],1)])), ...
    'gridStep',h,'seconds',toc(timer));
straight=norm(task.qGoal(1:3)-task.q0(1:3)); q.detourRatio=q.positionLengthM/max(straight,1e-12);
q.positionJerkSquaredIntegral=trapz(t,sum(jerk.^2,1)); q.angularJerkSquaredIntegral=trapz(t,sum(angularJerk.^2,1));
q.legAccelSquaredIntegral=trapz(t,sum(Ldd.^2,1)); q.legJerkSquaredIntegral=trapz(t,sum(legJerk.^2,1));
q.numerics='Analytic q,v,a; rotation-based omega,alpha; uniform-grid central differences for jerk and force rate.';
end
function d=derivative(x,h)
d=zeros(size(x)); d(:,2:end-1)=(x(:,3:end)-x(:,1:end-2))/(2*h);
d(:,1)=(-3*x(:,1)+4*x(:,2)-x(:,3))/(2*h); d(:,end)=(3*x(:,end)-4*x(:,end-1)+x(:,end-2))/(2*h);
end
