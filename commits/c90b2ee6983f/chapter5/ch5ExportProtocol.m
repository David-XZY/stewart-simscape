function protocol=ch5ExportProtocol()
% Export actual shared physical limits for independent raw-data auditing.
[c,root]=ch5Init();[m,~,~,strict]=ch5Physics(c);
protocol=struct('version',c.version,'Ts',c.Ts,'force_min',strict.forceMin, ...
    'force_max',strict.forceMax,'force_rate_limit',strict.forceRateLimit, ...
    'leg_length_min',m.lmin,'leg_length_max',m.lmax, ...
    'leg_speed_max',m.actuator.ldotMax,'leg_acceleration_max',m.actuator.lddotMax, ...
    'sigma_min',strict.sigmaSafe,'safe_distance',c.safe_distance,'passed',true);
file=fullfile(root,'chapter5','artifacts','validation','physical_parameters.json');
fid=fopen([file,'.pending'],'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(protocol));clear cleanup;movefile([file,'.pending'],file,'f');
end
