function projection=verifyAbfdEqualityProjection(oracle,kit,point,auditDir,checkpointHash)
% Recompute a proposed affine dependence certificate from the actual oracle.
% Only equalities with a bounded roundoff residual may be omitted internally.
import casadi.*
statusFile=fullfile(auditDir,'status.json'); dataFile=fullfile(auditDir,'affine_equality_audit.mat');
statusHash=abfdFileHash(statusFile); dataHash=abfdFileHash(dataFile);
audit=readAbfdJsonUtf8(statusFile); saved=load(dataFile,'details','kit'); details=saved.details;
assert(strcmp(audit.state,'complete') && audit.passed && audit.withinRoundoffBudget && ...
    strcmp(audit.oracleHash,kit.oracleHash) && strcmp(audit.checkpointHash,checkpointHash) && ...
    isequaln(saved.kit,kit),'ABFD:EqualityProjectionSource','Certificate must match the exact original problem and checkpoint.');
rows=details.affineRows(:); kept=details.keptRows(:); dependent=details.dependentRows(:);
assert(~isempty(dependent) && numel(unique(rows))==numel(rows) && ...
    isequal(sort([kept;dependent]),sort(rows)) && numel(unique([kept;dependent]))==numel(rows) && ...
    all(rows>=1 & rows<=numel(kit.bounds.lbg)) && all(rows==fix(rows)) && ...
    all(kit.bounds.lbg(rows)==kit.bounds.ubg(rows)) && ...
    isequal(sort(dependent),sort(audit.candidateDependentRows(:))), ...
    'ABFD:EqualityProjectionRows','Only a declared partition of original equality rows may be used.');
[~,keepLocal]=ismember(kept,rows); [~,dependentLocal]=ismember(dependent,rows);
C=details.coefficients;
assert(isequal(size(C),[numel(dependent),numel(kept)]) && all(isfinite(C(:))) && ...
    isequal(size(details.matrix),[numel(rows),numel(point.x)]) && ...
    numel(point.lam_g)==numel(kit.bounds.lbg) && all(isfinite(point.lam_g)), ...
    'ABFD:EqualityProjectionLayout','Invalid coefficient or original multiplier layout.');
x=MX.sym('original',numel(point.x),1); expressions=oracle.call({x},true,false);
affine=expressions{2}(rows)-kit.bounds.lbg(rows);
settings=struct('helper_options',struct('max_num_dir',1)); A=jacobian(affine,x,settings);
assert(~depends_on(A,x),'ABFD:EqualityProjectionNonlinear','A proposed row has nonlinear decision dependence.');
evaluate=Function('abfd_equality_certificate_values',{x},{A,affine}); [matrix,value]=evaluate(point.x);
matrix=sparse(matrix); offset=full(value)-matrix*point.x;
assert(norm(matrix-details.matrix,inf)<1e-12 && norm(offset-details.offset(:),inf)<1e-12, ...
    'ABFD:EqualityProjectionCoefficients','Saved coefficients differ from the actual original oracle.');
residual=matrix(dependentLocal,:)-C*matrix(keepLocal,:);
constant=offset(dependentLocal)-C*offset(keepLocal);
support=find(any(residual~=0,1)); magnitude=max(abs([kit.bounds.lbx,kit.bounds.ubx]),[],2);
assert(all(isfinite(magnitude(support))),'ABFD:EqualityDependencyBound', ...
    'Nonzero dependence errors on unbounded variables cannot be certified.');
bound=max([0;abs(constant)+abs(residual(:,support))*magnitude(support)]);
budget=kit.c.solverTolerance/100;
assert(isfinite(bound) && bound<=budget,'ABFD:EqualityDependencyBound', ...
    'The full original decision-box dependence bound exceeds the roundoff budget.');
mapped=point.lam_g; mapped(kept)=mapped(kept)+C.'*point.lam_g(dependent); mapped(dependent)=0;
gradientDifference=norm(matrix.'*(mapped(rows)-point.lam_g(rows)),inf);
assert(gradientDifference<1e-8,'ABFD:EqualityMultiplierMapping','Mapped original multipliers changed the Lagrangian gradient.');
assert(strcmp(abfdFileHash(statusFile),statusHash) && strcmp(abfdFileHash(dataFile),dataHash), ...
    'ABFD:EqualityProjectionChanged','Certificate inputs changed during verification.');
report=struct('enabled',true,'kind','verified-affine-dependence-v1','dependentOriginalRows',dependent, ...
    'keptAffineRows',kept,'boundedDependenceResidual',bound,'roundoffBudget',budget, ...
    'coefficientRowL1',full(sum(abs(C),2)),'multiplierGradientDifference',gradientDifference, ...
    'auditStatusHash',statusHash,'auditDataHash',dataHash, ...
    'implementationHash',abfdFileHash([mfilename('fullpath'),'.m']), ...
    'scope','Internal independent equality representation; original bounds and inequalities unchanged; every original constraint must still pass final strict verification');
projection=struct('keepOriginalRows',setdiff((1:numel(kit.bounds.lbg)).',dependent), ...
    'dependentOriginalRows',dependent,'mappedMultipliers',mapped,'report',report);
end
