function validateAbfdTemporalConditioning(provider,temporal,profile)
% A pilot covariance is meaningful only about its matching conditional mean.
if nargin<3, profile=[]; end
conditional=isfield(temporal,'conditioning');
observed=isstruct(provider) && isfield(provider,'biasCalibration');
if ~conditional
    assert(~observed,'ABFD:UncalibratedConditionalUncertainty', ...
        'An unconditioned temporal model cannot be used after static mean conditioning.');
    return;
end
assert(observed,'ABFD:TemporalConditioningMismatch', ...
    'This temporal model requires an independently observed static-balance provider.');
c=temporal.conditioning; b=provider.biasCalibration;
startup=strcmp(c.kind,'independent-initial-inertia-static-v2');
assert((strcmp(c.kind,'independent-initial-static-balance-v1') || startup) && ...
    strcmp(b.method,'independently measured static equilibrium world-wrench offset') && ...
    strcmp(temporal.status,'calibrated-pilot') && isfield(temporal,'staticNetworkHash') && ...
    strcmp(temporal.staticNetworkHash,abfdHash(provider.network)) && ...
    strcmp(temporal.originalDatasetHash,provider.network.datasetHash), ...
    'ABFD:TemporalConditioningMismatch','Conditional protocol, static network or pilot status differs.');
assert(strcmp(c.contextDatasetHash,temporal.timedDatasetHash) && ...
    c.contexts==numel(temporal.groups.train)+numel(temporal.groups.validation)+numel(temporal.groups.test) && ...
    isfinite(c.maxIndependentOffsetError) && c.maxIndependentOffsetError<1e-8 && c.maxIndependentOffsetError>=0, ...
    'ABFD:TemporalConditioningEvidence','Conditional observations were not independently verified.');
for hash={c.contextDatasetHash,c.tasksHash,c.verificationImplementationHash,b.calibrationFileHash,b.plantHash}
    assert(ischar(hash{1}) && ~isempty(regexp(hash{1},'^[0-9a-f]{64}$','once')), ...
        'ABFD:TemporalConditioningEvidence','Missing conditional source hash.');
end
validateattributes(b.pose,{'double'},{'real','finite','numel',6});
validateattributes(b.staticForce,{'double'},{'real','finite','numel',6});
validateattributes(b.wrenchOffset,{'double'},{'real','finite','numel',6});
assert(isfield(provider,'elasticity') && norm(provider.elasticity.referencePose-b.pose(:),inf)<1e-10, ...
    'ABFD:TemporalConditioningPose','Spring context and initial static observation differ.');
measurement=[];
if startup
    assert(isfield(provider.network,'meanAnchoring') && isfield(provider,'parameterCalibration') && ...
        strcmp(provider.network.meanAnchoring,'initial-static-state-v1') && ...
        strcmp(provider.parameterCalibration.calibrationHash,b.calibrationFileHash) && ...
        strcmp(provider.parameterCalibration.plantHash,b.plantHash) && ...
        strcmp(c.datasetAuditHash,provider.network.datasetAuditHash) && ...
        isfinite(c.maxIndependentInertiaError) && c.maxIndependentInertiaError>=0 && c.maxIndependentInertiaError<1e-8 && ...
        isfinite(c.maxIndependentLabelError) && c.maxIndependentLabelError>=0 && c.maxIndependentLabelError<1e-8, ...
        'ABFD:TemporalStartupMismatch','Independent inertia/label evidence differs from the anchored mean.');
    measurement=provider.parameterCalibration;
else
    assert(~isfield(provider.network,'meanAnchoring') && ~isfield(provider,'parameterCalibration'), ...
        'ABFD:TemporalStartupMismatch','Static-only uncertainty cannot accompany startup-inertia conditioning.');
end
base=buildDynamicsProvider(provider.nominalModel,'residual-B',provider.network,false,b.pose(:),measurement);
initial=base.evaluate(b.pose(:),zeros(6,1),zeros(6,1));
assert(strcmp(base.hash,b.baseProviderHash) && ...
    norm(initial.Jv.'*b.staticForce(:)-initial.W-b.wrenchOffset(:),inf)<1e-8 && ...
    norm(provider.inverse(b.pose(:),zeros(6,1),zeros(6,1))-b.staticForce(:),inf)<1e-8, ...
    'ABFD:TemporalConditioningBalance','Provider does not reproduce the independent static balance.');
if ~isempty(profile)
    assert(isfield(profile,'initialAppliedForce') && norm(profile.initialAppliedForce-b.staticForce(:),inf)<1e-8, ...
        'ABFD:TemporalConditioningPreload','Physical initial force differs from the observed equilibrium.');
    plain=rmfield(profile,'initialAppliedForce');
    assert(strcmp(abfdHash(plain),b.plantHash),'ABFD:TemporalConditioningPlant', ...
        'Static observation belongs to a different physical plant.');
end
% uncertaintyValidated intentionally remains false: pilot use is not coverage acceptance.
end
