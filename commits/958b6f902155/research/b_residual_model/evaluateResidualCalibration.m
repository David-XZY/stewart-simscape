function report=evaluateResidualCalibration(y,mu,variance)
assert(isequal(size(y),size(mu),size(variance)) && all(variance>0,'all'), ...
    'ABFD:Calibration','Invalid prediction dimensions or variances.');
r=y-mu;
report=struct('rmse',sqrt(mean(r.^2,1)),'nll',mean(.5*(log(2*pi*variance)+r.^2./variance),'all'), ...
    'coverage95',mean(abs(r)<=1.95996398454*sqrt(variance),1), ...
    'standardizedResidualMean',mean(r./sqrt(variance),1));
end
