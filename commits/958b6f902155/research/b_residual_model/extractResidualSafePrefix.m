function [session,report]=extractResidualSafePrefix(result,bundle,c)
% Identification-only policy: retain the initial uninterrupted safe interval.
% Two samples are removed at both boundaries so offline derivative stencils
% cannot straddle a rejected sample. Full-run control metrics remain unchanged.
log=result.log; t=log.t(:); n=numel(t);
assert(strcmp(log.forceSource,'measured-actuator-output'),'ABFD:ActualForceRequired','Actual measured force is required.');
assert(isequal(t,log.forceTime(:)) && all(diff(t)>0), ...
    'ABFD:ForceAlignment','Prefix extraction requires already aligned actual force samples.');
assert(all(isfinite([log.q(:);log.qd(:);log.qdd(:);log.actualForce(:)])), ...
    'ABFD:DatasetNonfinite','Nonfinite source session.');
model=bundle.model; scene=bundle.scene; margins=nan(4,n);
firstUnsafe=n+1; reason='end of recorded session';
for k=1:n
    if abs(cos(log.q(5,k)))<=1e-5, firstUnsafe=k; reason='RPY coordinate singularity'; break; end
    point=evaluatePathConstraintsAtPoint([log.q(:,k);log.qd(:,k)],log.actualForce(:,k),model,scene,log.qdd(:,k));
    required=scene.collision.safeDistance*ones(size(point.collisionDistances));
    if t(k)>scene.phase.durationApproach, required(1)=0; end
    margins(:,k)=[min(point.collisionDistances-required); ...
        min([point.L-model.lmin;model.lmax-point.L]); ...
        min([log.actualForce(:,k)-model.actuator.forceMin;model.actuator.forceMax-log.actualForce(:,k)]); ...
        point.sigmaMin-model.singularity.sigmaMinSafe];
    bad=find(margins(:,k)<-c.constraintTolerance,1);
    if ~isempty(bad)
        names={'collision clearance','leg travel','actual force range','transmission singularity'};
        firstUnsafe=k; reason=names{bad}; break;
    end
end
buffer=2; ids=(1+buffer):(firstUnsafe-1-buffer);
assert(numel(ids)>=20 && t(ids(end))-t(ids(1))>=.2, ...
    'ABFD:UnsafePrefix','No initial safe prefix of at least 0.2 seconds after derivative buffers (%s).',reason);
session=struct('t',t(ids).','forceTime',t(ids).','q',log.q(:,ids),'qd',log.qd(:,ids), ...
    'qdd',log.qdd(:,ids),'actualForce',log.actualForce(:,ids), ...
    'taskId',log.taskId,'loadId',log.loadId,'trajectoryId',log.trajectoryId,'forceSource',log.forceSource);
if isfield(log,'accelerationSource'), session.accelerationSource=log.accelerationSource; end
rejectedTime=[]; if firstUnsafe<=n, rejectedTime=t(firstUnsafe); end
report=struct('policy','initial-safe-prefix-v1','sourceSamples',n,'retainedSamples',numel(ids), ...
    'firstSourceIndex',ids(1),'lastSourceIndex',ids(end),'firstRejectedTime',rejectedTime, ...
    'stopReason',reason,'derivativeBufferSamples',buffer,'timeRange',t(ids([1,end])).', ...
    'minimumMargins',min(margins(:,ids),[],2),'prefixPassed',true, ...
    'fullRunEngineeringPassed',result.metrics.engineeringPassed,'fullRunBudgetPassed',result.metrics.budgetPassed, ...
    'fullRunCollisionViolations',result.metrics.collisionViolationCount, ...
    'scope','valid identification interval only; no full-trajectory or control-acceptance claim');
session.prefixAcceptance=report;
end
