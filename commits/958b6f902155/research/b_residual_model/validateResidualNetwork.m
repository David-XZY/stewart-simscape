function net = validateResidualNetwork(net,allowFixture)
if nargin<2, allowFixture=false; end
assert(net.schemaVersion==1 && strcmp(net.kind,'residual-wrench-tanh'), ...
    'ABFD:ResidualSchema','Unsupported residual asset.');
assert(strcmp(net.status,'trained') || (allowFixture && strcmp(net.status,'test-fixture')), ...
    'ABFD:UntrainedAsset','Test fixtures are not trained models.');
assert(numel(net.inputMean)==12 && numel(net.inputScale)==12 && ...
    all(net.inputScale>0) && all(isfinite([net.inputMean(:);net.inputScale(:)])), ...
    'ABFD:ResidualNormalization','Invalid normalization.');
assert(all(isfinite([net.physical.mass;net.physical.com(:);net.physical.inertia(:)])) && ...
    net.physical.mass>0 && numel(net.physical.com)==3 && isequal(size(net.physical.inertia),[3,3]), ...
    'ABFD:PhysicalParameters','Invalid physical parameters.');
I=net.physical.inertia;
if isfield(net,'meanAnchoring') || isfield(net.physical,'inferenceCalibration')
    assert(isfield(net,'meanAnchoring') && strcmp(net.meanAnchoring,'initial-static-state-v1') && ...
        isfield(net.physical,'inferenceCalibration') && ...
        strcmp(net.physical.inferenceCalibration.kind,'independent-initial-inertia-static-v2') && ...
        isequal(net.physical.inferenceCalibration.required,true) && isfield(net.physical,'elasticity'), ...
        'ABFD:ResidualMeanProtocol','Startup inertia and anchored mean must be supplied together.');
    assert(isfield(net,'datasetAudit') && net.datasetAudit.passed && strcmp(net.datasetAudit.state,'complete') && ...
        strcmp(net.datasetAudit.datasetHash,net.datasetHash), ...
        'ABFD:ResidualDatasetAudit','Anchored model requires an independent raw-observation dataset audit.');
end
if isfield(net.physical,'elasticity')
    elastic=net.physical.elasticity;
    assert(strcmp(elastic.reference,'initial-leg-length-v1'),'ABFD:ElasticitySchema', ...
        'Structured spring/damping requires initial-leg-length-v1.');
    validateattributes(elastic.stiffness,{'double'},{'scalar','real','finite','nonnegative'});
    validateattributes(elastic.damping,{'double'},{'scalar','real','finite','nonnegative'});
    assert(isequal(sort(string(elastic.trainingGroups(:))),sort(string(net.physical.trainingGroups(:)))), ...
        'ABFD:TrainingLeakage','Elasticity and inertia must use the same frozen training groups.');
end
assert(norm(I-I.','fro')<1e-9 && min(eig(I))>0 && ...
    min(eig(trace(I)/2*eye(3)-I))>=-1e-9,'ABFD:PhysicalInertia','Inertia must be physically realizable.');
if iscell(net.layers), net.layers=[net.layers{:}]; end
width=12;
for k=1:numel(net.layers)
    layer=net.layers(k);
    assert(size(layer.W,2)==width && size(layer.W,1)==numel(layer.b) && ...
        all(isfinite([layer.W(:);layer.b(:)])),'ABFD:NetworkShape','Invalid MLP layer.');
    width=size(layer.W,1);
end
assert(width==12,'ABFD:NetworkOutput','Expected 6 means and 6 log variances.');
assert(numel(net.outputScale)==6 && all(net.outputScale>0) && ...
    all(isfinite(net.outputScale)) && isfinite(net.varianceCalibration) && net.varianceCalibration>0, ...
    'ABFD:ResidualScale','Invalid output scale or calibration.');
end
