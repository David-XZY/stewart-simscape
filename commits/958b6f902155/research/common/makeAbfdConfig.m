function c = makeAbfdConfig(overrides)
if nargin<1, overrides=struct(); end
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
c=struct('schemaVersion',1,'seed',20260905,'modelMode','analytic', ...
    'plannerMode','ihsid','controllerMode','baseline-lqi', ...
    'designMode','sequential','plantProfile','matched','stateSource','direct', ...
    'simulator','simscape','residualFile','','proposalFile','', ...
    'trajectoryFile','','outputDir',fullfile(root,'results','abfd'), ...
    'sampleTime',0.01,'candidateCount',8,'refineCount',2, ...
    'solverMaxIterations',300,'solverMaxCpuTime',inf, ...
    'allowTestFixtures',false,'maxOuterIterations',5,'trustRadius',0.1, ...
    'convergenceTolerance',1e-3,'tubeSigma',1.96,'processSpectralDensity',1e-8*eye(12), ...
    'initialCovariance',diag([1e-6*ones(1,3),1e-6*ones(1,3),1e-5*ones(1,6)]), ...
    'Q',diag([1e4*ones(1,3),2500*ones(1,3),100*ones(1,6)]), ...
    'RF',eye(6)/120^2,'trackingWeight',1,'feedbackWeight',1, ...
    'balanceWeight',0.01,'sensitivityWeight',0.01,'dVariant','tvlqr', ...
    'constraintTolerance',1e-6,'dynamicsTolerance',1e-6, ...
    'feedbackBudget',120,'onlineP95Limit',0.01, ...
    'plantOverrides',struct(),'attitudePerturbation',zeros(3,1), ...
    'qpEnabled',false,'dobEnabled',false,'antiWindupEnabled',false,'governorEnabled',false);
fields=fieldnames(overrides);
for k=1:numel(fields)
    assert(isfield(c,fields{k}) || any(strcmp(fields{k},{'plannerProfile','predictionProfile','solverTolerance', ...
        'temporalFile','allowPilotTemporal','predictionMaxStep','solverFormulation','covarianceShootingInterval','staticBalanceFile', ...
        'solverHessianApproximation','solverContinuationCount','solverHessianAssembly','inertiaCalibrationFile', ...
        'solverMaxDerivativeDirections','solverDerivativeAssembly','plantInitializationFile','solverReductionMode','covarianceCoordinates','observerKernel'})), ...
        'ABFD:UnknownOption','Unknown option: %s',fields{k});
    c.(fields{k})=overrides.(fields{k});
end
validatestring(c.modelMode,{'analytic','residual-B'});
if isfield(c,'plantInitializationFile')
    assert(ischar(c.plantInitializationFile) && ~isempty(c.plantInitializationFile), ...
        'ABFD:PlantInitializationConfig','Shared physical initialization requires an explicit independent observation file.');
end
if isfield(c,'staticBalanceFile')
    assert(strcmp(c.modelMode,'residual-B') && ischar(c.staticBalanceFile) && ~isempty(c.staticBalanceFile), ...
        'ABFD:StaticBalanceConfig','Static balance conditioning requires B and an explicit observation file.');
end
if isfield(c,'inertiaCalibrationFile')
    assert(strcmp(c.modelMode,'residual-B') && ischar(c.inertiaCalibrationFile) && ...
        ~isempty(c.inertiaCalibrationFile) && isfield(c,'staticBalanceFile'), ...
        'ABFD:StartupInertiaConfig','Startup inertia requires B and the matching static observation.');
end
validatestring(c.plannerMode,{'ihsid','learned-warmstart-F'});
% Optional so legacy configurations and their checkpoint hashes stay stable.
if isfield(c,'plannerProfile'), validatestring(c.plannerProfile,{'legacy','guarded-exact-v1','guarded-adaptive-v2'}); end
if isfield(c,'solverFormulation')
    c.solverFormulation=validatestring(c.solverFormulation, ...
        {'full-space','hs-reduced','covariance-shooting','covariance-shooting-hs-reduced'});
    if ~strcmp(c.solverFormulation,'full-space')
        assert(isfield(c,'plannerProfile') && any(strcmp(c.plannerProfile,{'guarded-exact-v1','guarded-adaptive-v2'})), ...
            'ABFD:ReducedSolverProfile','HS reduction uses the guarded solver and full-space acceptance.');
    end
    if any(strcmp(c.solverFormulation,{'covariance-shooting','covariance-shooting-hs-reduced'}))
        assert(isfield(c,'predictionProfile') && any(strcmp(c.predictionProfile,{'sampled-hold-v2','actuator-var-v3'})), ...
            'ABFD:CovarianceShootingModel','Covariance shooting requires sampled-hold or full actuator/VAR prediction.');
        if ~isfield(c,'covarianceShootingInterval'), c.covarianceShootingInterval=.1; end
        validateattributes(c.covarianceShootingInterval,{'double'},{'scalar','positive','finite','>=',c.sampleTime});
        assert(abs(c.covarianceShootingInterval/c.sampleTime-round(c.covarianceShootingInterval/c.sampleTime))<1e-8, ...
            'ABFD:CovarianceCutClock');
        if strcmp(c.solverFormulation,'covariance-shooting-hs-reduced')
            assert(strcmp(c.predictionProfile,'sampled-hold-v2'), ...
                'ABFD:CombinedReductionModel','Combined elimination currently supports the sampled covariance model.');
        end
    end
end
if isfield(c,'solverReductionMode')
    c.solverReductionMode=validatestring(c.solverReductionMode,{'global-qr','local-midpoint'});
    assert(isfield(c,'solverFormulation') && any(strcmp(c.solverFormulation, ...
        {'hs-reduced','covariance-shooting-hs-reduced'})), ...
        'ABFD:ReductionModeConfig','An explicit HS elimination mode requires an HS-reduced formulation.');
end
if isfield(c,'covarianceCoordinates')
    c.covarianceCoordinates=validatestring(c.covarianceCoordinates,{'cholesky','symmetric'});
    assert(isfield(c,'solverFormulation') && any(strcmp(c.solverFormulation, ...
        {'covariance-shooting','covariance-shooting-hs-reduced'})) && ...
        isfield(c,'predictionProfile') && strcmp(c.predictionProfile,'sampled-hold-v2'), ...
        'ABFD:CovarianceCoordinatesConfig','Explicit coordinates require sampled-hold covariance shooting.');
end
if isfield(c,'predictionProfile')
    c.predictionProfile=validatestring(c.predictionProfile,{'legacy-continuous-v1','sampled-hold-v2','actuator-var-v3'});
    if strcmp(c.predictionProfile,'actuator-var-v3')
        assert(strcmp(c.modelMode,'residual-B') && isfield(c,'temporalFile') && ~isempty(c.temporalFile), ...
            'ABFD:TemporalConfig','actuator-var-v3 requires explicit B and temporal model files.');
    end
end
if isfield(c,'allowPilotTemporal'), validateattributes(c.allowPilotTemporal,{'logical'},{'scalar'}); end
if isfield(c,'predictionMaxStep'), validateattributes(c.predictionMaxStep,{'double'},{'scalar','positive','finite','<=',c.sampleTime}); end
if isfield(c,'solverTolerance')
    validateattributes(c.solverTolerance,{'double'},{'scalar','positive','finite','<=',c.constraintTolerance});
end
if isfield(c,'solverHessianApproximation')
    c.solverHessianApproximation=validatestring(c.solverHessianApproximation,{'exact','limited-memory'});
end
if isfield(c,'solverMaxDerivativeDirections')
    validateattributes(c.solverMaxDerivativeDirections,{'double'},{'scalar','integer','>=',1,'<=',64});
end
if isfield(c,'solverDerivativeAssembly')
    c.solverDerivativeAssembly=validatestring(c.solverDerivativeAssembly,{'automatic','grouped-moments'});
    if strcmp(c.solverDerivativeAssembly,'grouped-moments')
        actuatorMoments=isfield(c,'solverFormulation') && strcmp(c.solverFormulation,'covariance-shooting') && ...
            isfield(c,'predictionProfile') && strcmp(c.predictionProfile,'actuator-var-v3');
        sampledMoments=isfield(c,'solverFormulation') && any(strcmp(c.solverFormulation, ...
            {'covariance-shooting','covariance-shooting-hs-reduced'})) && ...
            isfield(c,'predictionProfile') && strcmp(c.predictionProfile,'sampled-hold-v2') && ...
            isfield(c,'covarianceCoordinates') && strcmp(c.covarianceCoordinates,'symmetric');
        assert(strcmp(c.designMode,'codesign-A') && (actuatorMoments || sampledMoments), ...
            'ABFD:GroupedDerivativeConfig', ...
            'Grouped derivatives require full actuator/VAR moments or symmetric sampled covariance shooting.');
        assert(~isfield(c,'solverHessianAssembly') || strcmp(c.solverHessianAssembly,'direct'), ...
            'ABFD:GroupedHessianConfig','Grouped Hessian blocks cannot be combined with compressed Hessian recovery.');
    end
end
if isfield(c,'solverContinuationCount')
    validateattributes(c.solverContinuationCount,{'double'},{'scalar','integer','nonnegative','finite'});
end
if isfield(c,'solverHessianAssembly')
    c.solverHessianAssembly=validatestring(c.solverHessianAssembly,{'direct','compressed'});
    assert(isfield(c,'solverHessianApproximation') && strcmp(c.solverHessianApproximation,'exact'), ...
        'ABFD:HessianAssemblyConfig','An explicit Hessian assembly requires exact Hessian selection.');
end
if isfield(c,'solverHessianApproximation') || isfield(c,'solverMaxDerivativeDirections') || ...
        (isfield(c,'solverContinuationCount') && c.solverContinuationCount>0)
    assert(isfield(c,'plannerProfile') && any(strcmp(c.plannerProfile,{'guarded-exact-v1','guarded-adaptive-v2'})), ...
        'ABFD:SolverNumericsProfile','Explicit Hessian/continuation settings require a guarded solver profile.');
end
validatestring(c.controllerMode,{'baseline-lqi','scheduled-lqi','fullstate-tvlqr','geometric-D'});
if isfield(c,'staticBalanceFile') && any(strcmp(c.controllerMode,{'fullstate-tvlqr','geometric-D'}))
    assert(isfield(c,'predictionProfile') && strcmp(c.predictionProfile,'actuator-var-v3'), ...
        'ABFD:StaticBalancePrediction','TVLQR/D experiments with static conditioning require matched actuator/VAR prediction.');
end
validatestring(c.designMode,{'sequential','codesign-A'});
validatestring(c.plantProfile,{'matched','high-fidelity'});
validatestring(c.stateSource,{'direct','external-observer'});
% Optional: preserve the original configuration and checkpoint hashes.
if isfield(c,'observerKernel')
    assert(ischar(c.observerKernel) && isrow(c.observerKernel) && ...
        any(strcmp(c.observerKernel,{'interval-rk4-v1','fused-rk4-v1'})) && ...
        strcmp(c.stateSource,'external-observer'),'ABFD:ObserverKernelConfig', ...
        'An explicit observer kernel requires a supported name and external-observer state source.');
end
validatestring(c.dVariant,{'d0','fixed','tvlqr'});
assert(strcmp(c.simulator,'simscape'),'ABFD:Simulator','Only existing Simscape is supported.');
validateattributes(c.sampleTime,{'double'},{'scalar','positive','finite'});
validateattributes(c.solverMaxIterations,{'double'},{'scalar','integer','positive','finite'});
validateattributes(c.solverMaxCpuTime,{'double'},{'scalar','real','positive','nonnan'});
validateattributes(c.candidateCount,{'double'},{'scalar','integer','positive'});
validateattributes(c.refineCount,{'double'},{'scalar','integer','positive','<=',c.candidateCount});
for name={'Q','RF','initialCovariance','processSpectralDensity'}
    a=c.(name{1}); dim=12; if strcmp(name{1},'RF'), dim=6; end
    validateattributes(a,{'double'},{'size',[dim,dim],'real','finite'});
    assert(norm(a-a.','fro')<1e-10 && ...
        min(eig(a))>=-1e-12,'ABFD:Covariance','Invalid %s.',name{1});
end
assert(all(eig(c.RF)>0),'ABFD:Cost','RF must be positive definite.');
validateattributes(c.maxOuterIterations,{'double'},{'scalar','integer','positive'});
validateattributes(c.trustRadius,{'double'},{'scalar','positive','finite'});
validateattributes(c.attitudePerturbation,{'double'},{'size',[3,1],'real','finite'});
assert(~strcmp(c.designMode,'codesign-A') || any(strcmp(c.controllerMode,{'fullstate-tvlqr','geometric-D'})), ...
    'ABFD:CodesignController','A requires its full-state TVLQR or geometric-D controller.');
end
