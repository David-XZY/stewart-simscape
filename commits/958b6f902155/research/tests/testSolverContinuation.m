function report=testSolverContinuation(outputDirectory)
% Independent convex optimum with an active nonlinear inequality. Bounded
% calls must converge using primal AND dual state without accepting timeout.
import casadi.*
x=MX.sym('x',2,1); target=[3;-1]; objective=sumsqr(x-target); constraint=dot(x,x);
options=struct('print_time',false,'ipopt',struct('print_level',0,'max_iter',2, ...
    'tol',1e-9,'acceptable_iter',0,'mu_strategy','monotone','mu_init',1e-6, ...
    'warm_start_init_point','yes','warm_start_bound_push',1e-9, ...
    'warm_start_bound_frac',1e-9,'warm_start_slack_bound_push',1e-9, ...
    'warm_start_slack_bound_frac',1e-9,'warm_start_mult_bound_push',1e-9));
problem=struct('x',x,'f',objective,'g',constraint);
solver=nlpsol('continuation_contract','ipopt',problem,options);
bounds=struct('lbx',[-4;-4],'ubx',[4;4],'lbg',-inf,'ubg',4); initial=[.1;.1];
[~,limited,limitedReport]=solveAbfdNlpWithContinuation(solver,bounds,initial,0);
assert(~limited.success && limitedReport.solverCalls==1 && limitedReport.iterations==2, ...
    'ABFD:ContinuationLimit','A bounded unfinished solve must remain unsuccessful.');
[sol,stats,continuation]=solveAbfdNlpWithContinuation(solver,bounds,initial,20,outputDirectory);
expected=2*target/norm(target); value=full(sol.x);
stationarity=2*(value-target)+2*value*full(sol.lam_g)+full(sol.lam_x);
assert(stats.success && continuation.continuations>0 && ...
    norm(value-expected)<1e-7 && norm(stationarity,inf)<1e-7 && ...
    abs(value.'*value-4)<1e-7 && full(sol.lam_g)>0, ...
    'ABFD:ContinuationOptimum','Continued solve did not satisfy the analytic constrained optimum and KKT conditions.');
assert(~continuation.history(1).usedPrimalDualStart && all([continuation.history(2:end).usedPrimalDualStart]), ...
    'ABFD:ContinuationState','All resumed segments must use their own preceding primal/dual state.');
loaded=load(fullfile(outputDirectory,sprintf('segment_%03d.mat',continuation.solverCalls)),'checkpoint');
assert(isequal(loaded.checkpoint.iterate.x,value) && isequal(loaded.checkpoint.bounds,bounds), ...
    'ABFD:ContinuationCheckpoint','Saved iterate and immutable bounds differ from the actual solve.');
report=struct('passed',true,'limitedStatus',limited.return_status,'finalStatus',stats.return_status, ...
    'calls',continuation.solverCalls,'iterations',continuation.iterations, ...
    'solutionError',norm(value-expected),'stationarityResidual',norm(stationarity,inf), ...
    'scope','Actual bounded IPOPT calls converge to the analytic constrained optimum; no Stewart trajectory acceptance');
end
