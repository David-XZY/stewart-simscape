function delivery=loadAbfdFrozenFResult(inputDir,snapshotDir,taskId)
% Validate a complete remote F task before any local closed-loop experiment.
transfer=readAbfdJsonUtf8(fullfile(snapshotDir,'transfer_manifest.json'));
assert(strcmp(transfer.state,'complete') && any(strcmp(transfer.taskIds,taskId)), ...
    'ABFD:FTransferTask','Task is absent from the completed transfer snapshot.');
paths={transfer.files.path}; assert(numel(unique(paths))==numel(paths),'ABFD:FTransferDuplicates');
prefix=[taskId,'/']; relevant=find(strncmp(paths,prefix,numel(prefix)));
assert(~isempty(relevant),'ABFD:FTransferTask','Task has no transferred files.');
required={[prefix,'manifest.json'],[prefix,'task_status.json'],[prefix,'warmstart_benchmark.json']};
assert(all(ismember(required,paths)),'ABFD:FTransferCoverage','Every task manifest and outcome file must be byte-hashed.');
for index=relevant
    relative=paths{index};
    assert(isempty(regexp(relative,'(^|[\\/])\.\.([\\/]|$)|:|^[\\/]','once')), ...
        'ABFD:FTransferPath','Transfer entries must stay inside the snapshot.');
    assert(strcmp(abfdFileHash(fullfile(snapshotDir,relative)),transfer.files(index).sha256), ...
        'ABFD:FTransferHash','Transferred artifact changed: %s',relative);
end
taskDirectory=fullfile(snapshotDir,taskId);
manifest=readAbfdJsonUtf8(fullfile(taskDirectory,'manifest.json'));
status=readAbfdJsonUtf8(fullfile(taskDirectory,'task_status.json'));
benchmark=readAbfdJsonUtf8(fullfile(taskDirectory,'warmstart_benchmark.json'));
assert(strcmp(status.state,'complete') && strcmp(status.taskId,taskId) && ...
    strcmp(status.manifestHash,abfdHash(manifest)) && strcmp(benchmark.status,'experiment-completed'), ...
    'ABFD:FTaskCompletion','Missing or mismatched native task completion.');
frozen=load(fullfile(inputDir,'frozen.mat'),'tasks','manifest','c');
indices=find(strcmp({frozen.tasks.taskId},taskId));
assert(isscalar(indices) && indices==manifest.taskIndex,'ABFD:FFrozenTask','Task index changed.');
task=frozen.tasks(indices); c=makeAbfdConfig(frozen.c);
assert(strcmp(task.split,'test') && strcmp(abfdHash(task),manifest.taskHash) && ...
    strcmp(manifest.taskHash,frozen.manifest.tasks(indices).taskHash), ...
    'ABFD:FFrozenTask','Frozen test task changed.');
assert(strcmp(abfdHash(rmfield(c,'outputDir')),manifest.configHash) && ...
    c.candidateCount==8 && c.refineCount==2 && strcmp(c.designMode,'sequential') && ...
    strcmp(c.modelMode,'analytic') && ~c.allowTestFixtures, ...
    'ABFD:FFrozenConfig','Original planning policy or configuration changed.');
assert(strcmp(benchmark.selectionPolicy,'ranked-top-k') && benchmark.candidateCount==8 && benchmark.refineCount==2, ...
    'ABFD:FRankingPolicy','Expected the frozen eight-to-two policy.');
audit=readAbfdJsonUtf8(fullfile(inputDir,'import_checks','model_audit.json'));
datasetHash=abfdFileHash(fullfile(inputDir,'proposal_dataset.json'));
assert(audit.passed && strcmp(audit.datasetHash,datasetHash) && strcmp(manifest.datasetHash,datasetHash), ...
    'ABFD:FDeliveryAudit','Training-data and weight audit mismatch.');
names={'geometric-single','nearest','mlp'};
assert(numel(status.methods)==3 && isequal({status.methods.method},names) && ...
    isequaln(status.methods,benchmark.summaries),'ABFD:FMethodCompleteness','All three method summaries must agree.');
p=buildDynamicsProvider(task.model); methods=struct('name',{},'planningPassed',{},'planning',{},'bundle',{},'provenance',{});
for k=1:3
    name=names{k}; rows=benchmark.records(strcmp({benchmark.records.method},name));
    expectedCount=8; if k==1, expectedCount=1; end
    assert(numel(rows)==expectedCount && isequal(sort([rows.candidate]),1:expectedCount) && ...
        all(strcmp({rows.taskId},taskId)) && all(~[rows.passed] | [rows.selected]) && ...
        sum([rows.selected])==status.methods(k).refinedCount && ...
        status.methods(k).passed==any([rows.passed]), ...
        'ABFD:FCandidateCompleteness','Missing, duplicated or inconsistent candidate outcomes.');
    assetHash=''; candidateError=0;
    methodDirectory=fullfile(taskDirectory,taskId,sprintf('method_%02d',k));
    if k>1
        asset=fullfile(inputDir,'models',name,'proposal_model.json'); assetHash=abfdFileHash(asset);
        assert(strcmp(assetHash,manifest.assetHashes{k}) && strcmp(assetHash,audit.([name,'AssetHash'])), ...
            'ABFD:FAssetHash','Frozen proposal model changed.');
        rankPath=[prefix,taskId,sprintf('/method_%02d/ranking.mat',k)];
        assert(any(strcmp(paths,rankPath)),'ABFD:FMissingRanking','Ranking is absent from the byte-hashed transfer.');
        rankingData=load(fullfile(methodDirectory,'ranking.mat'),'ranking','cp'); ranking=rankingData.ranking;
        candidates=sampleAbfdCandidates(task,asset,c.candidateCount,c.seed);
        assert(isequal(size(candidates),size(rankingData.cp)),'ABFD:FCandidateShape');
        candidateError=max(abs(candidates(:)-rankingData.cp(:)));
        assert(candidateError<1e-12,'ABFD:FCandidateReplay','Proposals differ from the saved frozen candidates.');
        [~,order]=sort(ranking.scores); selected=order(1:min(c.refineCount,numel(order)));
        selected=selected(isfinite(ranking.scores(selected)));
        assert(numel(ranking.scores)==8 && isequal(order,ranking.order) && isequal(selected,ranking.selected) && ...
            isequal(sort(selected(:)),sort([rows([rows.selected]).candidate].')), ...
            'ABFD:FSelectedCandidates','Refinement selection differs from the frozen ranking.');
    end
    provenance=struct('taskHash',manifest.taskHash,'datasetHash',datasetHash,'assetHash',assetHash, ...
        'remoteManifestHash',status.manifestHash,'remotePlannerHash',manifest.plannerHash, ...
        'candidateMaximumDifference',candidateError,'summary',status.methods(k),'records',rows, ...
        'bestFileHash','','selectedCandidate',[],'localReferencePassed',false);
    planning=[]; bundle=[];
    if status.methods(k).passed
        relative=[prefix,taskId,sprintf('/method_%02d/best_result.mat',k)];
        assert(any(strcmp(paths,relative)),'ABFD:FMissingBest','Accepted best result is absent from the transfer.');
        file=fullfile(methodDirectory,'best_result.mat'); saved=load(file,'best'); planning=saved.best;
        accepted=rows([rows.passed]); [minimum,index]=min([accepted.objective]);
        assert(planning.passed && planning.solverState.stats.success && planning.bundle.publishPassed && ...
            planning.maxEq<=c.constraintTolerance && planning.maxIneq<=c.constraintTolerance && ...
            abs(planning.objective-minimum)<1e-12 && abs(minimum-status.methods(k).bestObjective)<1e-12, ...
            'ABFD:FBestAcceptance','Best result was not the accepted minimum among the selected candidates.');
        assert(isequaln(planning.bundle.model,task.model) && isequaln(planning.bundle.scene,task.scene), ...
            'ABFD:FReferenceContext','Reference belongs to a different model or scene.');
        bundle=buildAbfdReferenceBundle(planning.bundle.refs.hs,task.model,task.scene,planning.disc,p,c);
        provenance.bestFileHash=abfdFileHash(file); provenance.selectedCandidate=accepted(index).candidate;
        provenance.localReferencePassed=bundle.publishPassed;
    end
    methods(k)=struct('name',name,'planningPassed',status.methods(k).passed,'planning',planning, ...
        'bundle',bundle,'provenance',provenance);
end
delivery=struct('task',task,'planningConfig',c,'methods',methods,'manifest',manifest, ...
    'frozenFileHash',abfdFileHash(fullfile(inputDir,'frozen.mat')), ...
    'transferManifestHash',abfdFileHash(fullfile(snapshotDir,'transfer_manifest.json')), ...
    'scope','Frozen F proposals, ranked refinement and complete HS references independently rechecked; no simulation acceptance');
end
