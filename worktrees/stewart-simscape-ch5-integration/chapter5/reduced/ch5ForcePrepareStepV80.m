function prepared=ch5ForcePrepareStepV80(x,previous,U,goal,o,firstPrior,r,k,time,qs)
% Shared physical linearization and quadratic objective; no candidate solves.
linear=ch5ForceLinearizeV66(x,previous,U,goal,o,r,k,time);
nodes=linear.nodes;M=linear.M;S=linear.S;n=r.plant.n;nv=54;H=r.c.H;
ps=[.1*ones(3,1);deg2rad(10)*ones(3,1)];vs=[.1*ones(3,1);.2*ones(3,1)];Pq=diag(ps);
term=ch5ForceTerminalV62(qs,r,k);e=([nodes(:,end);U(:,end)]-term.xi)./term.scale;
Je=[[S(:,:,end);M(end-5:end,:)],-term.steady_jacobian*Pq]./term.scale;
Jus=term.steady_jacobian(n+1:n+6,:)*Pq;L=chol(term.P,'lower');Md=M-[zeros(6,48);M(1:end-6,:)];D=diff([previous,U],1,2);
Jq=zeros(6*H,nv);Jg=Jq;Jv=Jq;
for j=1:H
    rows=6*(j-1)+(1:6);Jq(rows,:)=[S(1:6,:,j+1)./ps,-eye(6)];
    Jg(rows,:)=[S(1:6,:,j+1)./ps,zeros(6)];Jv(rows,:)=[S(7:12,:,j+1)./vs,zeros(6)];
end
J=[sqrt(r.c.Ts)*Jq;sqrt(r.c.Ts)*Jv;sqrt(.05*r.c.Ts)*Jg; ...
    sqrt(.01*r.c.Ts)*[Md/160,zeros(360,6)];sqrt(.001*r.c.Ts)*[M/2000,-repmat(Jus,H,1)/2000]; ...
    sqrt(.05*r.c.Ts)*[M/20,zeros(360,6)];[zeros(6,48),10*eye(6)];L'*Je];
res=[sqrt(r.c.Ts)*reshape((nodes(1:6,2:end)-qs)./ps,[],1);sqrt(r.c.Ts)*reshape(nodes(7:12,2:end)./vs,[],1); ...
    sqrt(.05*r.c.Ts)*reshape((nodes(1:6,2:end)-goal)./ps,[],1);sqrt(.01*r.c.Ts)*D(:)/160; ...
    sqrt(.001*r.c.Ts)*reshape(U-term.u,[],1)/2000;sqrt(.05*r.c.Ts)*(U(:)-firstPrior(:))/20;10*(qs-goal)./ps;L'*e];
Cterminal=L'*Je;et=L'*e;radius=sqrt(term.rho/(n+6));
linear.Q=2*(J'*J)+1e-6*eye(nv);linear.f=2*J'*res;
linear.A=[[linear.A,zeros(size(linear.A,1),6)];Cterminal;-Cterminal];
linear.b=[linear.b;radius-et;radius+et];linear.E=zeros(0,nv);linear.e=zeros(0,1);
priorJ=sqrt(.05*r.c.Ts)*[M/20,zeros(360,6)];priorRes=sqrt(.05*r.c.Ts)*(U(:)-firstPrior(:))/20;
prepared=struct('qp',ch5ForceQpPrepareV62(linear,r),'base_f',linear.f, ...
    'prior_gradient',2*.05*r.c.Ts*[M/400,zeros(360,6)]', ...
    'Qtask',linear.Q-2*(priorJ'*priorJ),'ftask',linear.f-2*priorJ'*priorRes, ...
    'task_base',sum(res.^2)-sum(priorRes.^2),'first_prior',firstPrior,'nodes',nodes, ...
    'x',x,'U',U,'qs',qs,'Pq',Pq,'terminal_rho',term.rho, ...
    'linearization_phases',linear.phase_seconds,'sensitivity',linear.sensitivity, ...
    'feedback',ch5ReducedFeedbackRolloutV50(r),'K',ch5ReducedFeedbackGain(x,r,k));
end
